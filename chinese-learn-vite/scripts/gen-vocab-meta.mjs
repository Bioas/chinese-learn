#!/usr/bin/env node
/**
 * Generates src/data/vocabMeta.js — a tiny (~24 KB) module with:
 *   TOTAL_WORDS        — full vocabulary size (Dashboard stat card)
 *   QUICK_STUDY_POOL   — deterministic ~98-word sample across all categories
 *                        (Dashboard Quick Study cards)
 *
 * The Dashboard currently imported VOCABULARY (6 MB chunk) just to show a
 * counter and shuffle a handful of random cards. With this meta module it no
 * longer needs to download the big vocabulary chunk on first paint.
 *
 * Regenerate after vocabulary data changes:
 *   node scripts/gen-vocab-meta.mjs
 */
import { readFile, writeFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(SCRIPT_DIR, '..', 'src', 'data', 'vocabMeta.js');

const { VOCABULARY } = await import('../src/data/vocabulary.js');

const TOTAL_WORDS = VOCABULARY.length;

// Deterministic sample: spread across categories, ~10 words each, then dedupe.
const byCat = {};
for (const w of VOCABULARY) {
  if (w.category === 'hsk') continue; // HSK is one giant list; sample from it evenly below
  (byCat[w.category] = byCat[w.category] || []).push(w);
}
const hsk = VOCABULARY.filter((w) => w.category === 'hsk');

const POOL_PER_CAT = 8;
const HSK_PER_LEVEL = 6;

const pool = [];
const seen = new Set();
const pick = (arr, n) => {
  const step = Math.max(1, Math.floor(arr.length / n));
  let added = 0;
  for (let i = 0; i < arr.length && added < n; i += step) {
    const w = arr[i];
    if (seen.has(w.chinese)) continue;
    seen.add(w.chinese);
    pool.push(w);
    added++;
  }
};

for (const cat of Object.keys(byCat)) pick(byCat[cat], POOL_PER_CAT);
const hskByLevel = {};
for (const w of hsk) (hskByLevel[w.subcategory] = hskByLevel[w.subcategory] || []).push(w);
for (const level of Object.keys(hskByLevel).sort()) pick(hskByLevel[level], HSK_PER_LEVEL);

// Compact shape — only the fields the Dashboard Quick Study cards need.
const QUICK_STUDY_POOL = pool.map((w) => ({
  id: w.id,
  chinese: w.chinese,
  pinyin: w.pinyin,
  meaning: w.meaning,
  meaningThai: w.meaningThai,
  category: w.category,
  subcategory: w.subcategory,
}));

const content = `// Auto-generated by scripts/gen-vocab-meta.mjs — do not edit by hand.
// Regenerate after vocabulary data changes:
//   npm run gen:vocab-meta   (also runs automatically before each build)
//
// Tiny subset of vocabulary stats so the Dashboard never downloads the full
// 6 MB VOCABULARY chunk on first paint.

export const TOTAL_WORDS = ${TOTAL_WORDS};

// Deterministic ~${pool.length}-word sample across categories + HSK levels.
export const QUICK_STUDY_POOL = ${JSON.stringify(QUICK_STUDY_POOL, null, 2)};
`;

await writeFile(OUT, content, 'utf8');
console.log(`Wrote ${OUT}`);
console.log(`TOTAL_WORDS: ${TOTAL_WORDS}, pool: ${QUICK_STUDY_POOL.length} words`);
